"""สร้าง Data/PosMenuSeed.cs จาก menu-import.json (รันครั้งเดียวตอนเตรียม deploy)"""
import json

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

data = json.load(open("glur.cafe.page/Data/menu-import.json", encoding="utf-8"))

folders = ",\n        ".join(
    f'("{esc(f["name"])}", "{f["icon"]}", {f["order"]}, {str(f["active"]).lower()})'
    for f in data["folders"])
items = ",\n        ".join(
    f'("{esc(i["folder"])}", "{esc(i["title"])}", '
    + (f'"{i["price"]}"' if i["price"] else "null")
    + f', {str(i["recommended"]).lower()}, {i["order"]})'
    for i in data["items"])

code = """// <auto-generated />
// Seed โครงเมนูจาก POS export (Export_Menu_Branch_2023681.xlsx)
// สร้างโดย scripts/import_menu.py — ห้ามแก้มือ ถ้าจะอัปเดตให้รันสคริปต์ใหม่
using glur.cafe.page.Models;

namespace glur.cafe.page.Data
{
    public static class PosMenuSeed
    {
        // (Name, Icon, DisplayOrder, IsActive)
        public static readonly (string Name, string Icon, int Order, bool Active)[] Folders =
        [
        %s
        ];

        // (FolderName, Title, Price, IsRecommended, DisplayOrder)
        public static readonly (string Folder, string Title, string? Price, bool Reco, int Order)[] Items =
        [
        %s
        ];
    }
}
""" % (folders, items)

open("glur.cafe.page/Data/PosMenuSeed.cs", "w", encoding="utf-8").write(code)
print("ok", len(code))
